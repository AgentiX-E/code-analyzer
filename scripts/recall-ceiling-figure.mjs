#!/usr/bin/env node
/**
 * **The one figure in this repository that is about what the reviewer did not produce.**
 *
 * Every other chart here plots accuracy against price, because that is the comparison a reader wants. This one plots a
 * single corpus's 330 goldens split by *where they went*, and the split is the reason the accuracy charts have looked
 * the way they have for twenty iterations: **71 emitted, 20 blocked by the budget, 13 dropped by a category rule, 226
 * with no candidate anywhere in the pool.** A campaign that keeps pricing devices against the first three bars is
 * pricing 31 % of the corpus, and §124.2's budget curve is the arithmetic that says so.
 *
 * **Generated from `benchmarks/recall-ceiling.json` and checked, not drawn by hand**, because the defect §121.5 found
 * was a hand-edited figure pointing at a run that had not produced it.
 *
 * ```
 * node scripts/recall-ceiling-figure.mjs            # write docs/aacr-recall-ceiling.svg
 * node scripts/recall-ceiling-figure.mjs --check    # exit 1 if the file on disk differs
 * ```
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const DATA = join(ROOT, 'benchmarks', 'recall-ceiling.json');
const OUT = join(ROOT, 'docs', 'aacr-recall-ceiling.svg');

const WIDTH = 760;
// **314 rather than 300, because the last legend note and the footer line were 11 pixels apart** and a footnote that
// touches the legend above it is read as part of that legend.
const HEIGHT = 314;
const BAR = { x: 24, y: 116, w: 712, h: 46 };

/** Four bars, four greys, and the last one in the colour this repository uses for a refuted claim. */
const FILL = ['#1f2328', '#6e7781', '#afb8c1', '#cf222e'];

function escape(text) {
  return String(text)
    .replace(/&/gu, '&amp;')
    .replace(/</gu, '&lt;')
    .replace(/>/gu, '&gt;')
    .replace(/"/gu, '&quot;');
}

/** **The segments must sum to the corpus**, and this is the check rather than the sentence: a bar that does not add up
 * is a bar whose last segment silently absorbed the arithmetic error. */
export function checkStages(data) {
  const total = data.stages.reduce((sum, stage) => sum + stage.goldens, 0);
  if (total !== data.provenance.goldens) {
    throw new Error(
      `the stages sum to ${String(total)} and the corpus is ${String(data.provenance.goldens)}: the bar would be a picture of a different corpus`,
    );
  }
  return total;
}

function render(data) {
  const goldens = checkStages(data);
  const parts = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${String(WIDTH)}" height="${String(HEIGHT)}" viewBox="0 0 ${String(WIDTH)} ${String(HEIGHT)}" role="img" aria-label="Where the ${String(goldens)} goldens of one AACR slice went">`,
    `<rect width="${String(WIDTH)}" height="${String(HEIGHT)}" fill="#ffffff" />`,
    `<text x="24" y="30" font-size="15" font-weight="700" fill="#1f2328">Where ${String(goldens)} goldens went, and the 68.5 % no emission rule can reach</text>`,
    `<text x="24" y="50" font-size="11" fill="#57606a">The R-55 arm: ${String(data.provenance.prs)} pull requests from row ${String(data.provenance.slice.skip)}, five shipped lanes, judge ${escape(data.provenance.judge)}</text>`,
    `<text x="24" y="66" font-size="9" fill="#8c959f">source: benchmarks/recall-ceiling.json, from run ${escape(data.provenance.runId)}; generated by scripts/recall-ceiling-figure.mjs - do not edit by hand</text>`,
  ];

  // **One bar, four segments, each labelled in place when it is wide enough and below when it is not.** A 13-golden
  // segment is 4 % of the width and a number inside it would be unreadable at any font size this figure can afford.
  let x = BAR.x;
  const label = [];
  data.stages.forEach((stage, at) => {
    const w = (stage.goldens / goldens) * BAR.w;
    parts.push(
      `<rect x="${String(x)}" y="${String(BAR.y)}" width="${String(w)}" height="${String(BAR.h)}" fill="${FILL[at]}" />`,
    );
    const inside = w > 40;
    parts.push(
      `<text x="${String(inside ? x + w / 2 : x + w / 2)}" y="${String(inside ? BAR.y + 20 : BAR.y + BAR.h + 16)}" text-anchor="middle" font-size="${inside ? '15' : '10'}" font-weight="${inside ? '700' : '600'}" fill="${inside ? '#ffffff' : FILL[at]}">${String(stage.goldens)}</text>`,
    );
    if (!inside) {
      parts.push(
        `<line x1="${String(x + w / 2)}" y1="${String(BAR.y + BAR.h)}" x2="${String(x + w / 2)}" y2="${String(BAR.y + BAR.h + 6)}" stroke="${FILL[at]}" stroke-width="1" />`,
      );
    }
    label.push({ at, x, w, stage });
    x += w;
  });

  // **The legend carries the share and the note**, because the share is the sentence and the note is why the segment
  // exists. Two lines per entry and a four-entry column, which is the space four rows of text need and no more.
  data.stages.forEach((stage, at) => {
    const y = 202 + at * 22;
    parts.push(
      `<rect x="26" y="${String(y - 8)}" width="9" height="9" fill="${FILL[at]}" />`,
      `<text x="44" y="${String(y)}" font-size="11" fill="#1f2328">${String(stage.goldens)} (${((stage.goldens / goldens) * 100).toFixed(1)} %) ${escape(stage.name)}</text>`,
      `<text x="44" y="${String(y + 11)}" font-size="9" fill="#8c959f">${escape(stage.note)}</text>`,
    );
  });

  parts.push(
    `<text x="24" y="${String(HEIGHT - 10)}" font-size="9" fill="#8c959f">the last segment is the one no ranking, budget or judge change can move; EVAL-CONTRACT §124.1</text>`,
    `</svg>`,
  );
  return parts.join('\n');
}

function main() {
  const argv = process.argv.slice(2);
  const check = argv.includes('--check');
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const svg = render(data);
  if (check) {
    let onDisk = '';
    try {
      onDisk = readFileSync(OUT, 'utf8');
    } catch {
      console.error(`${OUT} does not exist: run node scripts/recall-ceiling-figure.mjs`);
      process.exitCode = 1;
      return;
    }
    if (onDisk !== svg) {
      console.error(
        `${OUT} differs from what the data renders: run node scripts/recall-ceiling-figure.mjs`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(
      `recall-ceiling figure is current: ${String(data.provenance.goldens)} goldens in four stages`,
    );
    return;
  }
  writeFileSync(OUT, svg);
  console.log(
    `wrote ${OUT} (${String(svg.length)} bytes, ${String(data.provenance.goldens)} goldens)`,
  );
}

if (process.argv[1]?.endsWith('recall-ceiling-figure.mjs') === true) main();
